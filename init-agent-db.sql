-- Ayrotek Veri Marketi - Kurum İçi DMZ Yerel Veritabanı Başlatma Scripti
-- Bu tablo ve veriler SADECE kurumun kendi DMZ sınırları içerisinde kalır.
-- Ham veriler ASLA Coordinator'a veya diğer kurumlara gönderilmez.
-- =============================================================================

CREATE TABLE IF NOT EXISTS gelir_gider (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kurum_kod VARCHAR(50) NOT NULL,
    sube_ad VARCHAR(100) NOT NULL,
    kar BIGINT NOT NULL,
    gelir BIGINT NOT NULL,
    gider BIGINT NOT NULL,
    donem VARCHAR(20) NOT NULL,
    yil INT NOT NULL,
    olusturma_tarihi TIMESTAMPTZ DEFAULT NOW()
);

